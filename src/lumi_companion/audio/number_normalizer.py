"""数字表現の正規化モジュール。

テキスト内の数字表現（漢数字、ローマ数字、半角数字等）を全角数字に統一正規化するユーティリティを提供します。
"""

import re


class NumberNormalizer:
    """数字表現の正規化を行うクラス。"""

    @staticmethod
    def normalize(text: str) -> str:
        """テキスト内の数字表現（漢数字、ローマ数字、半角数字等）を全角数字に統一正規化する。

        Args:
            text (str): 対象文字列。

        Returns:
            str: 正規化済みの文字列。
        """
        # 1. 全角数字の半角化
        text = text.translate(str.maketrans("０１２３４５６７８９", "0123456789"))

        # 2. 丸数字の変換
        maru_map = {
            "①": "1",
            "②": "2",
            "③": "3",
            "④": "4",
            "⑤": "5",
            "⑥": "6",
            "⑦": "7",
            "⑧": "8",
            "⑨": "9",
            "⑩": "10",
            "⑪": "11",
            "⑫": "12",
            "⑬": "13",
            "⑭": "14",
            "⑮": "15",
            "⑯": "16",
            "⑰": "17",
            "⑱": "18",
            "⑲": "19",
            "⑳": "20",
        }
        for src, dst in maru_map.items():
            text = text.replace(src, dst)

        # 3. ローマ数字 (アルファベット及び特殊記号) の長順変換
        roman_map = [
            ("VIII", "8"),
            ("VII", "7"),
            ("III", "3"),
            ("VI", "6"),
            ("IV", "4"),
            ("IX", "9"),
            ("II", "2"),
            ("V", "5"),
            ("X", "10"),
            ("I", "1"),
            ("Ⅷ", "8"),
            ("Ⅶ", "7"),
            ("Ⅲ", "3"),
            ("Ⅵ", "6"),
            ("Ⅳ", "4"),
            ("Ⅸ", "9"),
            ("Ⅱ", "2"),
            ("Ⅴ", "5"),
            ("Ⅹ", "10"),
            ("Ⅰ", "1"),
        ]
        for r_src, r_dst in roman_map:
            text = text.replace(r_src, r_dst)

        # 4. 漢数字のシンプル変換
        kanji_map = [
            ("十", "10"),
            ("九", "9"),
            ("八", "8"),
            ("七", "7"),
            ("六", "6"),
            ("五", "5"),
            ("四", "4"),
            ("三", "3"),
            ("二", "2"),
            ("一", "1"),
            ("〇", "0"),
            ("ゼロ", "0"),
        ]
        for k_src, k_dst in kanji_map:
            text = text.replace(k_src, k_dst)

        # 「101」など（十1 -> 11）の補正
        text = re.sub(r"10([1-9])", r"1\1", text)

        # 全角数字に変換
        zenkaku_table = str.maketrans("0123456789", "０１２３４５６７８９")
        text = text.translate(zenkaku_table)

        return text
